#!/usr/bin/env python3
"""Makaledeki HER sayiyi sonuc.json + saglamlik.json'dan uretir.

    python3 sayilar.py   ->  paper/numbers.tex, paper/sekil_egri.tex

Makale metninde elle yazilmis veri sayisi olmaz; tablolar da uretilir. Iki
tablonun satirlari numbers.tex icinde MAKRO olarak durur (\\TabScanRows,
\\TabLateRows): tabular icinde \\input, ardindan gelen \\bottomrule'u
"Misplaced \\noalign" ile dusuruyor (ilk CI derlemesinde oldu).
"""
import json
import os

import numpy as np

B = os.path.dirname(os.path.abspath(__file__))
P = os.path.join(B, "paper")
M = {}


def reg(ad, deger, bicim="{}"):
    assert ad.isalpha(), ad
    M[ad] = bicim.format(deger)


def main():
    os.makedirs(P, exist_ok=True)
    s = json.load(open(os.path.join(B, "sonuc.json")))
    g = json.load(open(os.path.join(B, "saglamlik.json")))
    F, O, K = s["fonlar"], s["ozet"], s["kesif_fonu_AYRI"]
    G = {f["fon"]: f for f in g["fonlar"]}
    GO = g["ozet"]

    reg("NFunds", O["gecerli_fon"]); reg("NDropped", len(O["elenen"]))
    reg("WindowFirst", min(f["ilk"] for f in F)); reg("WindowLast", max(f["son"] for f in F))
    reg("NDaysMin", min(f["en_iyi"]["n"] for f in F)); reg("NDaysMax", max(f["fiyat_gunu"] for f in F))
    reg("PoneK", O["P1"]["tutan"]); reg("PoneNeed", O["P1"]["esik"])
    reg("PtwoK", O["P2"]["tutan"]); reg("PtwoNeed", O["P2"]["esik"])
    reg("PthreeK", O["P3"]["anlamli"]); reg("PthreeNeed", O["P3"]["esik"])
    reg("PfourK", O["P4"]["tutan"]); reg("PfourNeed", O["P4"]["esik"])
    reg("MedRefR", O["ref_r2_medyan"], "{:.2f}"); reg("MedBestR", O["en_iyi_r2_medyan"], "{:.2f}")
    reg("MedDR", O["dr2_medyan"], "{:.2f}")
    reg("MedBL", O["P3"]["b_L_medyan"], "{:.2f}"); reg("MedBE", O["P3"]["b_E_medyan"], "{:.2f}")
    zs = [f["P3"]["z_L"] for f in F]
    reg("MinZL", min(zs), "{:.1f}"); reg("MaxZL", max(zs), "{:.1f}")
    sp = O["P3"]["isaret_testi_p"]
    reg("SignP", f"{sp:.4f}")
    reg("RefKTwo", sum(1 for f in F if f["referans"]["secilen_k"] == 2))
    reg("MinRefR", min(f["en_iyi"]["ref_r2"] for f in F), "{:.2f}")
    reg("MaxRefR", max(f["en_iyi"]["ref_r2"] for f in F), "{:.2f}")
    reg("MinBestR", min(f["en_iyi"]["r2"] for f in F), "{:.2f}")
    reg("MaxBestR", max(f["en_iyi"]["r2"] for f in F), "{:.2f}")
    at17 = [f for f in F if f["en_iyi"]["h"] == "17:00" and f["en_iyi"]["k"] == 1]
    reg("AtSeventeen", len(at17))
    reg("EarlierHour", sum(1 for f in F if f["en_iyi"]["h"] < "17:00"))
    reg("AllKOne", sum(1 for f in F if f["en_iyi"]["k"] == 1))
    nq = [f for f in F if f["surucu"] == "NQ"]
    reg("NTech", len(nq)); reg("NBroad", len(F) - len(nq))
    reg("TechMedBestR", float(np.median([f["en_iyi"]["r2"] for f in nq])), "{:.2f}")
    # saglamlik (plan disi)
    reg("PlaceboSig", GO["plasebo_z_abs_gt_1.96"])
    reg("PlaceboMed", GO["plasebo_b_medyan"], "{:+.2f}")
    reg("FxRobustK", GO["kurlu_bL_pozitif_z_gt_1.645"])
    reg("MedRLate", GO["r2_yalniz_gec_seans_medyan"], "{:.2f}")
    reg("MedBetaRef", GO["beta_ref_medyan"], "{:.2f}"); reg("MedBetaBest", GO["beta_en_iyi_medyan"], "{:.2f}")
    reg("BetaRatio", GO["beta_en_iyi_medyan"] / GO["beta_ref_medyan"], "{:.1f}")
    reg("SeasonSame", GO["mevsim_ayni_saat"])
    us17 = [f["fon"] for f in at17]
    reg("SeasonSameAtSeventeen", sum(1 for k in us17 if G[k]["mevsim"]["yaz_EDT"]["h"] ==
                                     G[k]["mevsim"]["kis_EST"]["h"] == "17:00"))
    # kesif fonu
    reg("DiscHour", K["en_iyi"]["h"]); reg("DiscBestR", K["en_iyi"]["r2"], "{:.2f}")
    reg("DiscRefR", K["en_iyi"]["ref_r2"], "{:.2f}"); reg("DiscBL", K["P3"]["b_L"], "{:.2f}")
    reg("DiscZL", K["P3"]["z_L"], "{:.1f}")

    tik = lambda b: "\\checkmark" if b else "--"
    t1, t2 = [], []
    for x in F:
        e = x["en_iyi"]
        t1.append(f"{x['fon']} & {x['surucu']} & {e['n']} & {x['referans']['secilen_k']} & "
                  f"{e['ref_r2']:.3f} & {e['h']} & {e['k']} & {e['r2']:.3f} & ${e['dr2']:+.3f}$ & "
                  f"{x['yarilar']['yari1']['h']} / {x['yarilar']['yari2']['h']} & "
                  f"{tik(x['P1_saat'])} & {tik(x['P2_buyukluk_kararlilik'])} \\\\")
        p, q = x["P3"], G[x["fon"]]
        t2.append(f"{x['fon']} & {p['b_E']:.2f} ({p['se_E']:.2f}) & {p['b_L']:.2f} ({p['se_L']:.2f}) & "
                  f"{p['z_L']:.1f} & ${q['plasebo']['b_L_sonraki']:+.2f}$ ({q['plasebo']['se_sonraki']:.2f}) & "
                  f"{q['beta_ref']:.2f} & {q['beta_en_iyi']:.2f} & "
                  f"{q['mevsim']['yaz_EDT']['h']} / {q['mevsim']['kis_EST']['h']} \\\\")
    with open(os.path.join(P, "numbers.tex"), "w") as f:
        f.write("% GENERATED by sayilar.py from sonuc.json and saglamlik.json. Do not edit.\n")
        for k in sorted(M):
            f.write("\\newcommand{\\%s}{%s}\n" % (k, M[k]))
        for ad, satirlar in (("TabScanRows", t1), ("TabLateRows", t2)):
            f.write("\\newcommand{\\%s}{%%\n%s\n}\n" % (ad, "\n".join(satirlar)))
    for eski in ("tablo1.tex", "tablo2.tex"):
        if os.path.exists(os.path.join(P, eski)):
            os.remove(os.path.join(P, eski))
    # sekil koordinatlari saglamlik.py tarafindan uretiliyor; paper/ altina kopyala
    src = os.path.join(B, "sekil_egri.tex")
    if os.path.exists(src):
        open(os.path.join(P, "sekil_egri.tex"), "w").write(open(src).read())
    print(f"{len(M)} makro + 2 tablo makrosu -> {P}")
    for k in sorted(M):
        print(f"  {k:24s} {M[k]}")


if __name__ == "__main__":
    main()
